// -- WMO code → icon mapping ------------------------------------------
const sprite::Sprite& forWeatherCodeBig(int code) {
  switch (code) {
    case 0:                                              return SUN_BIG;
    case 1: case 2:                                      return PARTLY_CLOUDY_BIG;
    case 3:                                              return CLOUDY_BIG;
    case 45: case 48:                                    return FOG_BIG;
    case 51: case 53: case 55: case 56: case 57:
    case 61: case 66: case 80:                           return RAIN_BIG;
    case 63: case 65: case 67: case 81: case 82:        return HEAVY_RAIN_BIG;
    case 71: case 73: case 75: case 77: case 85: case 86: return SNOW_BIG;
    case 95: case 96: case 99:                           return THUNDERSTORM_BIG;
    default:                                             return PARTLY_CLOUDY_BIG;
  }
}

